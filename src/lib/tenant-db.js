
import { getOrgPool } from "@/lib/db.js";

const schemaStatements = [
  `CREATE TABLE IF NOT EXISTS roles (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    role_name VARCHAR(100) NOT NULL UNIQUE,
    description TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
  )`,
  `CREATE TABLE IF NOT EXISTS permissions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    permission_name VARCHAR(100) NOT NULL UNIQUE,
    description TEXT
  )`,
  `CREATE TABLE IF NOT EXISTS role_permissions (
    role_id BIGINT NOT NULL REFERENCES roles(id) ON DELETE CASCADE,
    permission_id BIGINT NOT NULL REFERENCES permissions(id) ON DELETE CASCADE,
    PRIMARY KEY (role_id, permission_id)
  )`,
  `CREATE TABLE IF NOT EXISTS employees (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    employee_code VARCHAR(100) UNIQUE,
    full_name VARCHAR(200) NOT NULL,
    email VARCHAR(255) NOT NULL UNIQUE,
    phone VARCHAR(50),
    job_title VARCHAR(150),
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
  )`,
  `CREATE TABLE IF NOT EXISTS amenity (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(200) NOT NULL,
    description TEXT,
    location VARCHAR(255),
    capacity INTEGER CHECK (capacity IS NULL OR capacity > 0),
    is_published BOOLEAN NOT NULL DEFAULT FALSE,
    created_by BIGINT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
  )`,
  `CREATE TABLE IF NOT EXISTS booking_history (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    booking_reference VARCHAR(50) NOT NULL UNIQUE,
    amenity_id BIGINT NOT NULL REFERENCES amenity(id),
    booked_by_name VARCHAR(200) NOT NULL,
    booked_by_email VARCHAR(255),
    start_time TIMESTAMPTZ NOT NULL,
    end_time TIMESTAMPTZ NOT NULL,
    status VARCHAR(30) NOT NULL DEFAULT 'pending',
    updated_by BIGINT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CHECK (end_time > start_time)
  )`,
  `CREATE TABLE IF NOT EXISTS users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    employee_id BIGINT REFERENCES employees(id) ON DELETE SET NULL,
    role_id BIGINT NOT NULL REFERENCES roles(id),
    full_name VARCHAR(200) NOT NULL,
    email VARCHAR(255) NOT NULL UNIQUE,
    password_hash TEXT NOT NULL,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
  )`,
  `CREATE INDEX IF NOT EXISTS idx_booking_amenity
    ON booking_history(amenity_id)`,
  `CREATE INDEX IF NOT EXISTS idx_booking_start_time
    ON booking_history(start_time)`,
  `CREATE INDEX IF NOT EXISTS idx_amenity_published
    ON amenity(is_published)`
];

const roleDefinitions = [
  ["Super Admin", "Full organization administration"],
  ["Operation Manager", "Amenity and booking operations"],
  ["Receptionist", "Booking and reception operations"]
];

const permissionDefinitions = [
  ["users.manage", "Create and manage organization users"],
  ["roles.manage", "Manage roles and permissions"],
  ["employees.manage", "Create and manage employees"],
  ["amenities.read", "View amenities"],
  ["amenities.manage", "Create and edit amenities"],
  ["amenities.publish", "Publish and unpublish amenities"],
  ["bookings.read", "View booking history"],
  ["bookings.create", "Create bookings"],
  ["bookings.update", "Update bookings and their status"]
];

const rolePermissions = {
  "Super Admin": permissionDefinitions.map(([name]) => name),
  "Operation Manager": [
    "employees.manage",
    "amenities.read",
    "amenities.manage",
    "amenities.publish",
    "bookings.read",
    "bookings.create",
    "bookings.update"
  ],
  Receptionist: [
    "amenities.read",
    "bookings.read",
    "bookings.create",
    "bookings.update"
  ]
};

export async function initializeTenantDatabase(databaseName) {
  const pool = getOrgPool(databaseName);
  const client = await pool.connect();

  try {
    await client.query("BEGIN");

    for (const statement of schemaStatements) {
      await client.query(statement);
    }

    for (const [roleName, description] of roleDefinitions) {
      await client.query(
        `INSERT INTO roles (role_name, description)
         VALUES ($1, $2)
         ON CONFLICT (role_name) DO NOTHING`,
        [roleName, description]
      );
    }

    for (const [permissionName, description] of permissionDefinitions) {
      await client.query(
        `INSERT INTO permissions (permission_name, description)
         VALUES ($1, $2)
         ON CONFLICT (permission_name) DO NOTHING`,
        [permissionName, description]
      );
    }

    for (const [roleName, permissionNames] of Object.entries(rolePermissions)) {
      for (const permissionName of permissionNames) {
        await client.query(
          `INSERT INTO role_permissions (role_id, permission_id)
           SELECT r.id, p.id
           FROM roles r
           CROSS JOIN permissions p
           WHERE r.role_name = $1
             AND p.permission_name = $2
           ON CONFLICT DO NOTHING`,
          [roleName, permissionName]
        );
      }
    }

    await client.query("COMMIT");

    return { success: true, databaseName };
  } catch (error) {
    await client.query("ROLLBACK").catch(() => {});
    throw error;
  } finally {
    // Release this connection, but keep the cached pool alive.
    client.release();
  }
}

export async function createTenantDatabase(databaseName) {
  if (
    typeof databaseName !== "string" ||
    !/^org_[a-z0-9]+$/.test(databaseName)
  ) {
    throw new Error("Invalid tenant database name");
  }

  const apiKey = process.env.NEON_API_KEY;
  const projectId = process.env.NEON_PROJECT_ID;
  const branchId = process.env.NEON_BRANCH_ID;
  const ownerName = process.env.NEON_DATABASE_OWNER || "neondb_owner";

  if (!apiKey || !projectId || !branchId) {
    throw new Error(
      "Missing NEON_API_KEY, NEON_PROJECT_ID, or NEON_BRANCH_ID"
    );
  }

  const endpoint =
    `https://console.neon.tech/api/v2/projects/` +
    `${encodeURIComponent(projectId)}/branches/` +
    `${encodeURIComponent(branchId)}/databases`;

  const headers = {
    Authorization: `Bearer ${apiKey}`,
    "Content-Type": "application/json",
    Accept: "application/json"
  };

  async function findDatabase() {
    const response = await fetch(endpoint, {
      method: "GET",
      headers
    });

    if (!response.ok) {
      throw new Error(
        `Unable to check Neon databases (HTTP ${response.status}).`
      );
    }

    const result = await response.json();
    const databases = result.databases || [];

    return databases.some((item) => {
      const name = item.database?.name || item.name;
      return name === databaseName;
    });
  }

  // Avoid creating a duplicate if a previous signup partially succeeded.
  if (await findDatabase()) {
    return { success: true, databaseName, alreadyExists: true };
  }

  const response = await fetch(endpoint, {
    method: "POST",
    headers,
    body: JSON.stringify({
      database: {
        name: databaseName,
        owner_name: ownerName
      }
    })
  });

  if (!response.ok) {
    // A concurrent signup may have created it after our initial check.
    if ([409, 422].includes(response.status)) {
      if (await findDatabase()) {
        return { success: true, databaseName, alreadyExists: true };
      }
    }

    const message = await response.text();

    throw new Error(
      `Neon database creation failed (HTTP ${response.status}): ` +
      message.slice(0, 500)
    );
  }

  return {
    success: true,
    databaseName,
    result: await response.json()
  };
}
